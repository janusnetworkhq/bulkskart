export interface TranscriptMessage {
  id?: string;
  senderName: string;
  role?: string;
  content: string;
  createdAt: string;
  attachmentName?: string | null;
  attachmentUrl?: string | null;
}

export interface TranscriptOptions {
  conversationId: string;
  participant1: { name: string; role: string; company?: string };
  participant2: { name: string; role: string; company?: string };
  topic?: string;
  productName?: string;
  messages: TranscriptMessage[];
}

export function exportChatTranscript(options: TranscriptOptions) {
  const { conversationId, participant1, participant2, topic, productName, messages } = options;
  const exportDate = new Date().toLocaleString('en-US', {
    dateStyle: 'full',
    timeStyle: 'medium',
  });

  // 1. Generate clean plain text format for direct file download
  let textContent = `======================================================================\n`;
  textContent += `BULKSKART B2B TRADE PLATFORM - OFFICIAL NEGOTIATION TRANSCRIPT\n`;
  textContent += `======================================================================\n\n`;
  textContent += `Conversation Reference: ${conversationId}\n`;
  textContent += `Generated On:           ${exportDate}\n`;
  textContent += `Topic / Purpose:        ${topic || 'Bulk Procurement Negotiation'}\n`;
  if (productName) {
    textContent += `Product Reference:      ${productName}\n`;
  }
  textContent += `\nPARTIES INVOLVED:\n`;
  textContent += `  • Party A (${participant1.role}): ${participant1.name} ${participant1.company ? `(${participant1.company})` : ''}\n`;
  textContent += `  • Party B (${participant2.role}): ${participant2.name} ${participant2.company ? `(${participant2.company})` : ''}\n`;
  textContent += `\nTOTAL RECORDS: ${messages.length} messages\n`;
  textContent += `----------------------------------------------------------------------\n\n`;

  messages.forEach((msg, idx) => {
    const timeStr = new Date(msg.createdAt).toLocaleString();
    textContent += `[${idx + 1}] ${timeStr} | ${msg.senderName} (${msg.role || 'Member'}):\n`;
    textContent += `    ${msg.content || '[File/Attachment]'}\n`;
    if (msg.attachmentName) {
      textContent += `    📎 Attachment: ${msg.attachmentName} (${msg.attachmentUrl || ''})\n`;
    }
    textContent += `\n`;
  });

  textContent += `======================================================================\n`;
  textContent += `END OF NEGOTIATION RECORD\n`;
  textContent += `This document is generated by BulkSkart for trade audit, contract records,\n`;
  textContent += `and dispute verification purposes.\n`;
  textContent += `======================================================================\n`;

  // Trigger file download
  const blob = new Blob([textContent], { type: 'text/plain;charset=utf-8' });
  const url = URL.createObjectURL(blob);
  const a = document.createElement('a');
  a.href = url;
  a.download = `BulkSkart-Negotiation-${conversationId.slice(0, 8)}-${Date.now()}.txt`;
  document.body.appendChild(a);
  a.click();
  document.body.removeChild(a);
  URL.revokeObjectURL(url);

  // 2. Also open formatted Print / Save as PDF view
  const printWindow = window.open('', '_blank');
  if (printWindow) {
    const html = `
      <!DOCTYPE html>
      <html>
      <head>
        <title>BulkSkart Negotiation Transcript - ${conversationId.slice(0, 8)}</title>
        <style>
          body { font-family: -apple-system, BlinkMacSystemFont, "Segoe UI", Roboto, Helvetica, Arial, sans-serif; color: #111827; padding: 40px; max-width: 800px; margin: 0 auto; line-height: 1.6; }
          .header { border-bottom: 2px solid #7C3AED; padding-bottom: 20px; margin-bottom: 24px; }
          .title { font-size: 22px; font-weight: 800; color: #111827; margin: 0; }
          .subtitle { font-size: 13px; color: #6B7280; margin-top: 4px; }
          .meta-box { background: #F9FAFB; border: 1px solid #E5E7EB; border-radius: 8px; padding: 16px; margin-bottom: 24px; font-size: 13px; }
          .meta-row { display: flex; justify-content: space-between; margin-bottom: 6px; }
          .meta-label { font-weight: 600; color: #4B5563; }
          .messages { display: flex; flex-direction: column; gap: 12px; }
          .msg { border: 1px solid #E5E7EB; border-radius: 8px; padding: 12px 16px; }
          .msg-header { display: flex; justify-content: space-between; font-size: 12px; margin-bottom: 6px; }
          .msg-sender { font-weight: 700; color: #7C3AED; }
          .msg-time { color: #9CA3AF; }
          .msg-body { font-size: 14px; white-space: pre-wrap; word-break: break-word; }
          .attachment { margin-top: 8px; font-size: 12px; color: #2563EB; font-weight: 500; }
          .footer { margin-top: 36px; padding-top: 16px; border-top: 1px solid #E5E7EB; font-size: 11px; color: #9CA3AF; text-align: center; }
          @media print {
            body { padding: 20px; }
            button { display: none; }
          }
        </style>
      </head>
      <body>
        <div class="header">
          <div style="display: flex; justify-content: space-between; align-items: center;">
            <h1 class="title">BulkSkart Trade Negotiation Transcript</h1>
            <button onclick="window.print()" style="background:#7C3AED; color:white; border:none; padding:8px 16px; border-radius:6px; font-weight:600; cursor:pointer;">Print / Save as PDF</button>
          </div>
          <div class="subtitle">Official B2B audit & contractual record • Reference ID: ${conversationId}</div>
        </div>

        <div class="meta-box">
          <div class="meta-row"><span class="meta-label">Generated:</span> <span>${exportDate}</span></div>
          <div class="meta-row"><span class="meta-label">Party A (${participant1.role}):</span> <span>${participant1.name} ${participant1.company ? `(${participant1.company})` : ''}</span></div>
          <div class="meta-row"><span class="meta-label">Party B (${participant2.role}):</span> <span>${participant2.name} ${participant2.company ? `(${participant2.company})` : ''}</span></div>
          <div class="meta-row"><span class="meta-label">Subject / Purpose:</span> <span>${topic || 'Bulk Procurement & Negotiation'}</span></div>
          ${productName ? `<div class="meta-row"><span class="meta-label">Product:</span> <span>${productName}</span></div>` : ''}
          <div class="meta-row"><span class="meta-label">Total Messages:</span> <span>${messages.length}</span></div>
        </div>

        <div class="messages">
          ${messages.map(m => `
            <div class="msg">
              <div class="msg-header">
                <span class="msg-sender">${m.senderName} (${m.role || 'Member'})</span>
                <span class="msg-time">${new Date(m.createdAt).toLocaleString()}</span>
              </div>
              <div class="msg-body">${m.content || '<em>[File Attachment]</em>'}</div>
              ${m.attachmentName ? `<div class="attachment">📎 Attachment: ${m.attachmentName}</div>` : ''}
            </div>
          `).join('')}
        </div>

        <div class="footer">
          BulkSkart B2B Marketplace • Verified Negotiation Record • Confidential & Legally Binding Upon Counterparty Sign-off
        </div>
      </body>
      </html>
    `;
    printWindow.document.write(html);
    printWindow.document.close();
  }
}

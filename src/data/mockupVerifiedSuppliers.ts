export function findMockupCompany(slugOrId: string): Company | undefined {
  if (!slugOrId) return undefined;
  const clean = slugOrId.trim().toLowerCase();

  // 1. Direct ID or slug match
  const direct = MOCKUP_VERIFIED_COMPANIES.find(
    c => c.id.toLowerCase() === clean || c.slug.toLowerCase() === clean
  );
  if (direct) return direct;

  // 2. Normalized name match
  const nameMatch = MOCKUP_VERIFIED_COMPANIES.find(
    c => c.company_name.toLowerCase().replace(/[^a-z0-9]/g, '-') === clean ||
         clean.includes(c.slug.toLowerCase()) ||
         c.slug.toLowerCase().includes(clean)
  );
  if (nameMatch) return nameMatch;

  return undefined;
}
